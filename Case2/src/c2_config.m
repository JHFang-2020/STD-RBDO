function cfg = c2_config(overrides)
%C2_CONFIG Mechanical parameters of the Case 2 beam (HF model and loads).
%   CFG=C2_CONFIG(struct('nElem',160,'dt',0.0005)) overrides only the listed fields.
%   SI units: m, s, N, Pa, kg. No surrogate or learning parameters are set here.
cfg = struct('L',12,'b',0.12,'E0',210e9,'rho',7850, ...
    'sigmaH',0.03,'sigmaE',0.05,'TL',4,'T',6, ...
    'P0',[16e3 12e3],'ell',[0.045 0.065]*12, ...
    'omega',[18 78],'phi',[0 pi/3],'loadLogScale',0.20, ...
    'loadCorrelation',0.35,'dampingGamma',0.8, ...
    'stressAllow',160e6,'targetPf',0.01,'designBounds',[0.16 0.30], ...
    'nElem',80,'dt',0.001,'samplePtsPerElem',5,'nGauss',6, ...
    'newmarkBeta',0.25,'newmarkGamma',0.5,'loadChunkSize',256, ...
    'responseMode','dynamic','nearPeakTolerance',0.02, ...
    'activeStressFraction',0.01,'competitionRatio',0.90, ...
    'competitionSeparationFraction',0.12,'switchJumpFraction',0.12, ...
    'pilotDeflectionRatioFlag',0.02,'pilotRotationFlag',0.10, ...
    'pilotElasticStressFlag',250e6,'schemaVersion','case2-hf-v1');
if nargin>0 && ~isempty(overrides)
    names=fieldnames(overrides);
    for j=1:numel(names)
        assert(isfield(cfg,names{j}),'c2:UnknownOption','unknown option: %s',names{j});
        cfg.(names{j})=overrides.(names{j});
    end
end
validateattributes(cfg.nElem,{'numeric'},{'scalar','integer','>=',2});
validateattributes(cfg.dt,{'numeric'},{'scalar','positive'});
validateattributes(cfg.samplePtsPerElem,{'numeric'},{'scalar','integer','>=',2});
assert(abs(cfg.T/cfg.dt-round(cfg.T/cfg.dt))<1e-8,'c2:TimeGrid','T/dt must be an integer');
assert(cfg.T>=cfg.TL && cfg.TL>0 && cfg.L>0);
assert(cfg.newmarkBeta==0.25 && cfg.newmarkGamma==0.5, ...
    'c2:Integrator','only the average-acceleration Newmark scheme (beta = 1/4, gamma = 1/2) is implemented');
assert(any(strcmp(cfg.responseMode,{'dynamic','quasistatic'})));
end
